#!/usr/bin/env node
/**
 * UX-DS-35 Stage02: one-way typed React CSS-variable contract.
 * Source dependency: design-system/tokens.json -> generated design-tokens.css -> this TS file.
 * This produces references only, never duplicates raw color/spacing/type values.
 */
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const cssPath=path.join(root,"site/assets/design-tokens.css");
const tokenPath=path.join(root,"design-system/tokens.json");
const target=path.join(root,"design-system/generated/css-token-refs.ts");
const pattern=/^\s*(--[a-z0-9-]+):\s*[^;]+;/gm;
function extract(css){
  const result=[...css.matchAll(pattern)].map((x)=>x[1]);
  if(!result.length)throw new Error("no CSS custom properties found");
  if(new Set(result).size!==result.length)throw new Error("duplicate CSS variable names");
  return result;
}
function render(css){
  const names=extract(css);
  const items=names.map((name)=>"  "+JSON.stringify(name)+": "+JSON.stringify("var("+name+")")+",");
  return [
    "/**",
    " * GENERATED from site/assets/design-tokens.css (which is generated from design-system/tokens.json).",
    " * Source: tools/generate_design_token_types.mjs. Do not edit this file.",
    " * References preserve runtime CSS inheritance; they DO NOT assert G2 approval or rendered parity.",
    " */",
    "export const liCssTokenRefs = {",
    ...items,
    "} as const;",
    "",
    "export type LiCssTokenName = keyof typeof liCssTokenRefs;",
    "export type LiCssTokenReference = (typeof liCssTokenRefs)[LiCssTokenName];",
    "",
    "export function liTokenRef(name: LiCssTokenName): LiCssTokenReference {",
    "  return liCssTokenRefs[name];",
    "}",
    ""
  ].join("\n");
}
function selfTest(){
  assert.deepEqual(extract(":root {\n --paper: #fff;\n --li-space-1: 4px;\n }"),["--paper","--li-space-1"]);
  assert.throws(()=>extract(":root {\n --paper: #fff;\n --paper: #eee; }"),/duplicate/);
  assert.throws(()=>extract("body { color: red; }"),/no CSS/);
  const a=render(":root {\n --paper: #fff; }");
  assert.ok(a.includes('"--paper": "var(--paper)"'));
  assert.ok(!a.includes("#fff"),"Raw color must not be copied to TS");
  console.log("PASS Stage02 generated token-ref parser: unique names, negative duplicates, no copied raw values");
}
const args=process.argv.slice(2);
if(args.includes("--self-test")){selfTest();process.exit(0);}
const source=JSON.parse(fs.readFileSync(tokenPath,"utf8"));
if(!source.schemaVersion||!source.colors||!source.semanticColors)throw new Error("canonical token source invalid");
const css=fs.readFileSync(cssPath,"utf8");
if(!css.includes("GENERATED from design-system/tokens.json"))throw new Error("input CSS was not generator-owned");
const content=render(css);
if(args.includes("--check")){
  if(!fs.existsSync(target)||fs.readFileSync(target,"utf8")!==content){
    console.error("FAIL generated React CSS variable refs stale; run node tools/generate_design_token_types.mjs");
    process.exit(1);
  }
  console.log("PASS Stage02: "+extract(css).length+" CSS names have 1:1 typed references, no duplicated values");
}else{
  fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,content,"utf8");
  console.log("Wrote design-system/generated/css-token-refs.ts ("+extract(css).length+" CSS variables)");
}
